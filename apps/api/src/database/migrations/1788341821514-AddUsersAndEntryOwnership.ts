// staged shape and this is the expand step; Day 10 performs the contract once
// real users exist and every entry has one.
//
// ---
//
// **The SQL below was generated by `pnpm migration:generate`, and it rebuilds
// the whole table rather than altering it.** That was read before it was
// trusted, and it is worth seeing rather than assuming, because it is not what
// the file appears to say.
//
// SQLite's `ALTER TABLE` can add a column but cannot add a `FOREIGN KEY`
// constraint to an existing table at all — a constraint is part of the stored
// `CREATE TABLE` text, and the only way to change that text is to write a new
// table, copy the rows across, drop the original and rename. TypeORM knows
// this, and every SQLite migration that touches a constraint looks like the
// dance below.
//
// It does the dance **twice**: once to add `user_id`, then again to add the
// foreign key onto it. One rebuild would have been enough. That is a wasted
// copy of the table and it is left exactly as generated — it is correct, it is
// inside a transaction, and hand-editing generated SQL to save one pass over a
// journal with five rows in it would trade a real risk for nothing.
//
// The dance is only safe because foreign key enforcement is off while it runs.
// TypeORM's `BetterSqlite3QueryRunner.beforeMigration` issues
// `PRAGMA foreign_keys = OFF` and `afterMigration` puts it back to `ON`;
// without that, `DROP TABLE "entries"` in the middle of the second rebuild
// would be checked against constraints pointing at a table that is about to
// come back under the same name.

