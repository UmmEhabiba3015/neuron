// `users`, and the column on `entries` that points at it. ADR-009's finding was
// that no column in this table could hold the answer to "whose entry is this?",
// so even a server that knew perfectly well who was asking would have nowhere
// to look it up. This migration is that column. Nothing checks it yet.
//
// **`user_id` is nullable, deliberately.** No user can exist until registration
// arrives on Day 9, so `NOT NULL` today would need either a fictional
// placeholder owner or the deletion of every row already in the journal. Both
