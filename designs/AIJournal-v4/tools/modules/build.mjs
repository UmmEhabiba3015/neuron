// A fixture is drawn once per frame width, so the same ids would meet on one page: each frame's ids take
// its name as a prefix, and so do the attributes that point at them (labels, ARIA, lists, forms, local links).
const ID_REFS = ['for', 'aria-labelledby', 'aria-describedby', 'aria-controls', 'aria-owns', 'aria-activedescendant', 'aria-details', 'aria-errormessage', 'list', 'form'];
function scopeIds(rendered, prefix) {
  const markup = String(rendered);
  const ids = new Set([...markup.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]));
  if (!ids.size) return markup;
  const to = id => ids.has(id) ? `${prefix}-${id}` : id;
  return markup
    .replace(/(\sid=")([^"]+)"/g, (all, a, id) => `${a}${to(id)}"`)
    .replace(new RegExp(`(\\s(?:${ID_REFS.join('|')})=")([^"]*)"`, 'g'), (all, a, v) => `${a}${v.split(/\s+/).map(to).join(' ')}"`)
    .replace(/(\shref="#)([^"]+)"/g, (all, a, id) => `${a}${to(id)}"`);
}
const duplicateIds = markup => {
  const seen = new Set(), twice = new Set();
  for (const [, id] of markup.matchAll(/\sid="([^"]+)"/g)) (seen.has(id) ? twice : seen).add(id);
  return [...twice];
};
