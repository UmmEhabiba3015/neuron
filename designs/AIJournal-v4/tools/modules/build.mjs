// The module build. Reads every module folder under the configured modules path and writes:
//   <dist>/system.css            tokens, base and every module, each in its cascade layer
//   <dist>/system.js             one classic script: the runtime plus every module's init
//   <dist>/assets/fonts.css      the fonts, embedded, in their own file
//   <dist>/css/...               the same CSS split per layer and module (catalogue pages use these)
//   <dist>/catalogue/<name>.html one page per module: tokens, base, the module and its uses only
//   <dist>/catalogue/index.html  the module inventory
//   <dist>/contracts/<name>.json and <dist>/types/<Name>.props.d.ts   the API for developers
//   <dist>/modules.json          name, layer, version, uses and consumers of every module
// and rewrites ASSETS.md, DESIGN.md's token values, and the TOKENS / BASE / MODULES marker blocks
// of any legacy stylesheet listed in "inject". Everything opens from file://: no module scripts,
// no fetch.
//
//   node tools/modules/build.mjs [project folder]      (scripts/build.mjs usually calls it)
