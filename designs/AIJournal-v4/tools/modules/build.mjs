// A parent gives a child its placement role (data-place) where it composes it: use(dep, { place })
// stamps the role on the child's root tag, so the child's own render never knows where it sits
// (decision 2026-10-12: a child says its role with data-place; the parent places by role).
// A child's role (place), its hooks (hook: data-hook) and its attribute hooks (data: { name: value } as
// data-<name>) go on its root, as the parent renders it.
const placed = (out, place, hook, data) => {
  const add = [place && ['data-place', place], hook && ['data-hook', hook], ...Object.entries(data || {}).map(([k, v]) => [`data-${k}`, v])].filter(Boolean);
  if (!add.length) return out;
  return new Markup(out.text.replace(/^(\s*<[a-z][\w-]*)([\s>/])/i, (m, open, next) => `${open}${add.map(([k, v]) => v === true ? ` ${k}` : ` ${k}="${String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;')}"`).join('')}${next}`));
};
// attrs (pages auth round, DESIGN.md 2026-10-14): a page sets the standard attributes of a module's root
// element (id, type, autocomplete, required, aria-*, hidden): the element's own HTML, as a parent sets it
// on a native element. It replaces an attribute the root already has (type="button" becomes type="submit");
// false removes one. class and style stay the module's; data-* goes through data.
const rooted = (out, attrs) => {
  const entries = Object.entries(attrs || {});
  if (!entries.length) return out;
  for (const [k] of entries) if (k === 'class' || k === 'style' || k.startsWith('data-')) throw new Error(`use() attrs: ${k} is not set this way (class and style are the module's; data-* goes through data)`);
  const esc = v => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  return new Markup(out.text.replace(/^(\s*<[a-z][\w-]*)([^>]*?)(\s*\/?>)/i, (m, open, rest, close) => {
    for (const [k, v] of entries) {
      rest = rest.replace(new RegExp(`\\s${k}(?:="[^"]*")?(?=[\\s/>]|$)`), '');
      if (v === false || v === null || v === undefined) continue;
      rest += v === true ? ` ${k}` : ` ${k}="${esc(v)}"`;
    }
    return open + rest + close;
  }));
};
const unplaced = p => { if (!p) return p; const { place, hook, data, attrs, mix, ...rest } = p; return rest; };
// mix (pages round 4b): the calling module's class on the dependency's root (state-message's line is the text
// module's line carrying aj-s-state-message too). true is the caller's root class, a string one of its parts.
const mixed = (out, mix, root, layer) => {
  if (!mix) return out;
  if (layer === 'pages') throw new Error('use() mix: a page has no class of its own to mix');
  const cls = mix === true ? root : `${root}__${mix}`;
  return new Markup(out.text.replace(/^(\s*<[a-z][\w-]*[^>]*?\sclass=")([^"]*)"/i, (m, open, list) => `${open}${list} ${cls}"`));
};

// Renders a module with its props and slots. `use` is limited to the modules the contract
// declares, so an undeclared dependency fails the build as well as the checks.
export async function makeRenderer(cfg, modules) {
  const byName = new Map(modules.map(m => [m.name, m]));
  const fns = new Map();
  for (const m of modules) if (m.render) fns.set(m.name, (await loadModule(m.render)).default);
  const renderOne = (name, props = {}, slots = {}) => {
    const mod = byName.get(name);
    const fn = fns.get(name);
    if (!fn) throw new Error(`${name}: no ${name}.html.mjs render function`);
    const allowed = new Set(usesOf(mod.contract).map(u => u.name));
    const kit = {
      html, raw, attrs, root: mod.root,
      el: part => `${mod.root}__${part}`,
      use: (dep, p, s) => {
        if (!allowed.has(dep)) throw new Error(`${name} renders ${dep}, which its contract does not list in "uses"`);
        return rooted(mixed(placed(renderOne(dep, unplaced(p), s), p?.place, p?.hook, p?.data), p?.mix, mod.root, mod.layer), p?.attrs);
      },
    };
    const out = fn(props, Object.fromEntries(Object.entries(slots).map(([k, v]) => [k, v instanceof Markup ? v : raw(v ?? '')])), kit);
    if (!(out instanceof Markup)) throw new Error(`${name}: render must return html\`\``);
    return out;
  };
  return { render: renderOne, byName };
}

// Fixtures are an array, or a function of { html, raw, use } returning one (for composites that
// place their declared modules in slots).
export async function loadFixtures(mod, renderer) {
  if (!mod.fixtures) return [];
  const exp = (await loadModule(mod.fixtures)).default;
  if (typeof exp !== 'function') return exp || [];
  const allowed = new Set(usesOf(mod.contract).map(u => u.name));
  return exp({ html, raw, use: (dep, p, s) => {
    if (!allowed.has(dep)) throw new Error(`${mod.name} fixtures render ${dep}, which the contract does not list in "uses"`);
    return rooted(placed(renderer.render(dep, unplaced(p), s), p?.place, p?.hook, p?.data), p?.attrs);
  } });
}

function fontsCss(cfg) {
  if (!cfg.fonts) return '';
  const manifestFile = join(cfg.root, cfg.fonts);
  const dir = dirname(manifestFile);
  const manifest = JSON.parse(read(manifestFile));
  const licences = [...new Set(manifest.faces.map(f => f.license).filter(Boolean))]
    .map(f => `/* ${f}\n${read(join(dir, f)).replace(/\*\//g, '* /').trim()}\n*/`);
  const faces = manifest.faces.map(f => {
    const data = readFileSync(join(dir, f.file)).toString('base64');
    const format = f.file.endsWith('.woff2') ? 'woff2' : f.file.endsWith('.woff') ? 'woff' : 'truetype';
    return `@font-face{font-family:"${f.alias}";font-style:${f.style || 'normal'};font-weight:${f.weight};font-display:swap;src:url(data:font/${format};base64,${data}) format("${format}")${f.unicode ? `;unicode-range:${f.unicode}` : ''}}`;
  });
  return licences.join('\n') + '\n' + faces.join('\n') + '\n';
}

// Replaces /* <NAME> START...*/ ... /* <NAME> END */ in a file. The markers must already exist:
// a project places them where it wants the generated CSS to sit.
export function replaceBlock(text, name, body, file) {
  const re = new RegExp(`(/\\* ${name} START[^*]*\\*/\\n?)[\\s\\S]*?(/\\* ${name} END \\*/)`);
  if (!re.test(text)) throw new Error(`${file}: missing the /* ${name} START ... */ ... /* ${name} END */ markers`);
  return text.replace(re, (_, start, end) => `${start}${body}${end}`);
}

// DESIGN.md: the "tokens:" key of the YAML front matter is rewritten from tokens.json; every
// other key and the whole body are left alone.
export function designDocWithTokens(text, tokens) {
  const lines = ['tokens:'];
  for (const [group, body] of Object.entries(tokens)) {
    if (group.startsWith('$')) continue;
    lines.push(`  ${group}:`);
    for (const t of flattenTokens({ [group]: body })) lines.push(`    ${t.name.slice(2)}: ${JSON.stringify(String(t.value))}`);
  }
  const block = lines.join('\n');
  const fm = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!fm) return `---\n${block}\n---\n\n${text}`;
  const kept = fm[1].split('\n');
  const out = []; let skipping = false;
  for (const l of kept) {
    if (/^tokens:\s*$/.test(l)) { skipping = true; continue; }
    if (skipping && (/^\s/.test(l) || l === '')) continue;
    skipping = false; out.push(l);
  }
  return `---\n${[...out.filter((l, i, a) => !(l === '' && i === a.length - 1)), block].join('\n')}\n---\n${text.slice(fm[0].length)}`;
}

const tsType = spec => {
  if (Array.isArray(spec?.values)) return spec.values.map(v => JSON.stringify(v)).join(' | ');
  switch (spec?.type) {
    case 'boolean': return 'boolean';
    case 'number': return 'number';
    case 'markup': case 'node': return 'ReactNode';
    case 'list': return 'string[]';
    default: return 'string';
  }
};
const doc = (text, indent = '  ') => text ? `${indent}/** ${String(text).replace(/\*\//g, '* /')} */\n` : '';

export function propsTypes(mod) {
  const c = mod.contract;
  const name = pascal(c.name);
  let body = '';
  for (const [k, v] of Object.entries(c.variants || {})) body += doc(`${v.description || ''} Default: ${JSON.stringify(v.default)}.`.trim()) + `  ${camel(k)}?: ${tsType(v)};\n`;
  for (const [k, v] of Object.entries(c.options || {})) body += doc(v.description) + `  ${camel(k)}?: ${tsType(v)};\n`;
  for (const [k, v] of Object.entries(c.content || {})) body += doc(v.description) + `  ${camel(k)}${v.required ? '' : '?'}: ${tsType(v)};\n`;
  for (const [k, v] of Object.entries(c.slots || {})) {
    const key = k === 'default' || k === 'children' ? 'children' : camel(k);
    body += doc(`${v.description || ''}${v.accepts ? ` Accepts: ${[].concat(v.accepts).join(', ')}.` : ''}`.trim()) + `  ${key}${v.required ? '' : '?'}: ReactNode;\n`;
  }
  for (const s of ['disabled', 'selected', 'loading', 'error', 'empty']) {
    if (/^yes/i.test(String(c.states?.[s] ?? ''))) body += doc(String(c.states[s]).replace(/^yes:?\s*/i, '')) + `  ${s}?: boolean;\n`;
  }
  for (const [k, v] of Object.entries(c.events || {})) {
    const detail = v.detail && Object.keys(v.detail).length ? `{ ${Object.entries(v.detail).map(([dk, dv]) => `${camel(dk)}: ${dv}`).join('; ')} }` : 'void';
    body += doc(v.when) + `  on${pascal(k)}?: (detail: ${detail}) => void;\n`;
  }
  const usesReact = /ReactNode/.test(body);
  return `// GENERATED by tools/modules/build.mjs from ${mod.rel}/contract.json. Do not edit.\n`
    + `// ${c.description || ''}\n// Class names stay as they are (${mod.root}); see the contract for tokens and states.\n`
    + (usesReact ? `import type { ReactNode } from 'react';\n\n` : '\n')
    + `export interface ${name}Props {\n${body}}\n`;
}

