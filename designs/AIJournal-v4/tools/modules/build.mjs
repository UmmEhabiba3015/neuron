function summaryTable(c) {
  const rows = [];
  for (const [k, v] of Object.entries(c.variants || {})) rows.push(['variant', k, `${v.values.join(' · ')} (default ${v.default})`]);
  for (const [k, v] of Object.entries(c.options || {})) rows.push(['option', k, v.values ? v.values.join(' · ') : v.type || '']);
  for (const [k, v] of Object.entries(c.content || {})) rows.push(['content', k, `${v.type || 'text'}${v.required ? ', required' : ''}`]);
  for (const [k, v] of Object.entries(c.slots || {})) rows.push(['slot', k, [].concat(v.accepts || 'any').join(', ')]);
  for (const [k, v] of Object.entries(c.events || {})) rows.push(['event', `${c.name}:${k}`, v.when || '']);
  for (const t of c.tokens?.reads || []) rows.push(['token', t, 'reads']);
  for (const [t, d] of Object.entries(c.tokens?.exposes || {})) rows.push(['token', t, `exposed: ${d}`]);
  for (const s of REQUIRED_STATES) if (c.states?.[s] !== undefined) rows.push(['state', s, String(c.states[s])]);
  for (const { name, version } of usesOf(c)) rows.push(['uses', name, version]);
  return `<table class="cat-table"><tbody>${rows.map(r => `<tr><td>${r.map(escape).join('</td><td>')}</td></tr>`).join('')}</tbody></table>`;
}

export async function build(projectRoot = process.cwd(), { log = console.log } = {}) {
  const cfg = loadConfig(projectRoot);
  if (!cfg) throw new Error('design-ci.json has no "modules" key: not a modular project.');
  const root = cfg.root;
  const dist = join(root, cfg.dist);
  const modules = discoverModules(cfg);
  for (const m of modules) {
    if (m.contractError) throw new Error(`${m.rel}: ${m.contractError}`);
    if (m.contract.name !== m.name) throw new Error(`${m.rel}: contract name "${m.contract.name}" does not match the folder`);
    if (m.contract.layer !== m.layer) throw new Error(`${m.rel}: contract layer "${m.contract.layer}" does not match the folder`);
  }
  const tokens = readTokens(cfg);
  const baseCss = existsSync(join(root, cfg.base)) ? read(join(root, cfg.base)) : '';

  for (const d of ['css', 'catalogue', 'contracts', 'types']) rmSync(join(dist, d), { recursive: true, force: true });

  // CSS
  const tokensLayer = layered('tokens', tokensCss(tokens));
  const baseLayer = layered('base', baseCss);
  write(join(dist, 'css', 'tokens.css'), BANNER(cfg.tokens) + LAYER_STATEMENT + '\n' + tokensLayer);
  write(join(dist, 'css', 'base.css'), BANNER(cfg.base) + baseLayer);
  const moduleCss = [];
  for (const layer of LAYERS) for (const m of modules.filter(x => x.layer === layer && x.css)) {
    const text = `/* ${m.name} ${m.contract.version} (${m.rel}) */\n` + layered(layer, read(m.css));
    moduleCss.push(text);
    write(join(dist, 'css', layer, `${m.name}.css`), BANNER(m.rel) + text);
  }
  write(join(dist, 'system.css'), BANNER(`${cfg.tokens}, ${cfg.base} and ${cfg.modules}`) + LAYER_STATEMENT + '\n' + tokensLayer + baseLayer + moduleCss.join(''));
  const fonts = fontsCss(cfg);
  if (fonts) write(join(dist, 'assets', 'fonts.css'), BANNER(cfg.fonts) + fonts);

  // JS
  const g = globalName(cfg);
  let js = `/* GENERATED by tools/modules/build.mjs. Do not edit. */\n` + read(join(here, 'runtime.js')).replace('__GLOBAL__', g);
  for (const m of modules.filter(x => x.script)) {
    js += `\n/* ${m.name} ${m.contract.version} (${m.rel}) */\n(function (register) {\n'use strict';\n${read(m.script).trim()}\n})(window.${g}.register);\n`;
  }
  write(join(dist, 'system.js'), js);

  // Catalogue, contracts, types
  const renderer = await makeRenderer(cfg, modules);
  const consumers = new Map(modules.map(m => [m.name, []]));
  for (const m of modules) for (const u of usesOf(m.contract)) consumers.get(u.name)?.push(m.name);
  const fontLink = fonts ? ['assets/fonts.css'] : [];
  for (const m of modules) {
    const c = m.contract;
    write(join(dist, 'contracts', `${m.name}.json`), JSON.stringify(c, null, 2) + '\n');
    write(join(dist, 'types', `${pascal(m.name)}.props.d.ts`), propsTypes(m));
    if (!m.render) continue;
    const deps = closure(m, renderer.byName);
    const links = [...fontLink, 'css/tokens.css', 'css/base.css', ...[...deps, m].filter(x => x.css).map(x => `css/${x.layer}/${x.name}.css`)];
    const fixtures = await loadFixtures(m, renderer);
    // A frame is a containing block, as the product shell is, so an overlay (position:absolute)
    // stays inside it; contract.catalogue.height gives an overlay's frame its height.
    const frameHeight = Number(c.catalogue?.height) || 0;
    const widths = [Number(c.catalogue?.width) || 390, ...Object.keys(c.responsive || {}).map(Number).filter(Boolean)];
    const sections = fixtures.map((f, i) => {
      const markup = renderer.render(m.name, f.props || {}, f.slots || {});
      const fw = f.width ? [f.width] : widths;
      return `<section class="cat-fixture" id="f${i}"><h2 class="cat-label">${escape(f.name)}</h2>${f.note ? `<p class="cat-note">${escape(f.note)}</p>` : ''}`
        + `<div class="cat-row">${fw.map(w => `<div class="cat-frame" style="--cat-w:${w}px${frameHeight ? `;--cat-h:${frameHeight}px` : ''}" data-width="${w}">${scopeIds(markup, `f${i}-${w}`)}</div>`).join('')}</div></section>`;
    }).join('\n');
    const twice = duplicateIds(sections);
    if (twice.length) throw new Error(`catalogue/${m.name}.html: the id(s) ${twice.join(', ')} appear more than once in one fixture's frame; give each its own id`);
    const body = `<header class="cat-head"><p class="cat-nav"><a class="cat-link" href="index.html">All modules</a></p>`
      + `<h1 class="cat-title">${escape(c.name)}</h1><p class="cat-meta">${escape([c.layer, c.version, c.inventory].filter(Boolean).join(' · '))} · <code>${m.root}</code></p>`
      + `<p class="cat-text">${escape(c.description || '')}</p></header>\n`
      + summaryTable(c) + '\n' + sections;
    write(join(dist, 'catalogue', `${m.name}.html`), page({ title: `${c.name} · catalogue`, depth: 1, links, body, cfg }));
  }
  const inventory = modules.map(m => ({ name: m.name, layer: m.layer, version: m.contract.version, inventory: m.contract.inventory || null, class: m.root, uses: usesOf(m.contract).map(u => u.name), consumers: consumers.get(m.name), contract: `contracts/${m.name}.json`, catalogue: `catalogue/${m.name}.html` }));
  write(join(dist, 'modules.json'), JSON.stringify(inventory, null, 2) + '\n');
  const indexRows = inventory.map(x => `<tr><td><a class="cat-link" href="${x.name}.html">${x.name}</a></td><td>${x.layer}</td><td>${x.version}</td><td>${x.inventory || ''}</td><td><code>${x.class}</code></td><td>${x.uses.join(', ')}</td><td>${x.consumers.join(', ')}</td></tr>`).join('');
  write(join(dist, 'catalogue', 'index.html'), page({ title: 'Module catalogue', depth: 1, links: [...fontLink, 'css/tokens.css', 'css/base.css'], cfg, scripts: false,
    body: `<header class="cat-head"><h1 class="cat-title">Module catalogue</h1><p class="cat-text">${modules.length} modules. Each page loads only the tokens, the base, the module and the modules it uses. Add <code>?together</code> to load the whole system.</p></header>`
      + `<table class="cat-table"><thead><tr><th>Module</th><th>Layer</th><th>Version</th><th>Inventory</th><th>Class</th><th>Uses</th><th>Used by</th></tr></thead><tbody>${indexRows}</tbody></table>` }));

  // Documents
  if (cfg.assetsDoc) write(join(root, cfg.assetsDoc), assetsDoc(cfg, modules));
  if (cfg.designDoc && existsSync(join(root, cfg.designDoc))) {
    const f = join(root, cfg.designDoc); const before = read(f); const after = designDocWithTokens(before, tokens);
    if (after !== before) writeFileSync(f, after);
  }

  // Legacy stylesheets that still carry the product while it migrates.
  for (const target of cfg.inject || []) {
    const f = join(root, target.file);
    let text = read(f); const before = text;
    if (target.tokens) text = replaceBlock(text, 'TOKENS', LAYER_STATEMENT + '\n' + tokensLayer, target.file);
    if (target.base) text = replaceBlock(text, 'BASE', baseLayer, target.file);
    if (target.modules) text = replaceBlock(text, 'MODULES', moduleCss.join(''), target.file);
    // A review stylesheet (presentation furniture outside the system) goes in its own block.
    if (target.review) text = replaceBlock(text, 'REVIEW', read(join(root, target.review)).trim() + '\n', target.file);
    if (text !== before) writeFileSync(f, text);
  }
  log(`Built ${modules.length} module(s) into ${cfg.dist}/ (system.css, system.js, catalogue, contracts, types)`);
  return { cfg, modules };
}

function assetsDoc(cfg, modules) {
  let out = `<!-- GENERATED by tools/modules/build.mjs from the module contracts${cfg.fonts ? ` and ${cfg.fonts}` : ''}. Do not edit: list a module's assets in its contract.json. -->\n# Assets\n\nEvery image, icon, video and font, where it is used, its source and licence, and any placeholder still to replace.\n`;
  if (cfg.fonts) {
    const manifest = JSON.parse(read(join(cfg.root, cfg.fonts)));
    out += `\n## Fonts\n\n| Font | File | Weight | Licence | Used |\n| --- | --- | --- | --- | --- |\n`;
    for (const f of manifest.faces) out += `| ${f.alias} | \`${dirname(cfg.fonts)}/${f.file}\` | ${f.weight} | ${f.license || ''} | embedded in every stylesheet; \`${cfg.dist}/assets/fonts.css\` |\n`;
  }
  const rows = modules.flatMap(m => (m.contract.assets || []).map(a => ({ m, a })));
  out += `\n## Module assets\n\n`;
  if (!rows.length) out += 'No module lists an asset yet.\n';
  else {
    out += `| Module | Asset | Used for | Source | Licence | Placeholder |\n| --- | --- | --- | --- | --- | --- |\n`;
    for (const { m, a } of rows) out += `| ${m.name} | ${a.file ? `\`${a.file}\`` : a.name || ''} | ${a.used || ''} | ${a.source || ''} | ${a.licence || a.license || ''} | ${a.placeholder ? 'yes: ' + a.placeholder : 'no'} |\n`;
  }
  return out;
}

