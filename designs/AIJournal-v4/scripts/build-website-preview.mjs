// Build one portable, edge-to-edge website preview from the three web walkthroughs.
import fs from 'node:fs';
import {openTag} from '../tools/lib/html-structure.mjs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources={
 mobile:'journal-prototype.html',
 tablet:'journal-prototype-tablet.html',
 desktop:'journal-prototype-desktop.html'
};
// Page CSS joins lock.css in @layer legacy, so it keeps the precedence it had over lock.css
// before the stylesheet moved into cascade layers (unlayered CSS would outrank every layer).
const siteCss=`
html{height:100%}
body{display:block;width:100%;min-height:100dvh;margin:0;padding:0;background:var(--paper);overflow-x:clip}
.screen.site-current{display:block}
.aj-l-stage__chrome,.aj-l-stage__caption,.motion-review-status{display:none!important}
/* The website uses the full viewport; the 560px tablet page belongs to the design comps. */
.aj-l-stage[data-platform="tablet"] .aj-c-panel{left:var(--rail);right:0}
/* The 360px desktop binding column can grow by 10%, then stops at 396px. */
.aj-l-stage[data-platform="desktop"] .aj-l-shell{--title-w:clamp(360px,25vw,396px)}
.aj-l-stage[data-platform="desktop"] .aj-c-panel{left:calc(var(--title-w) + var(--rail));right:0}
/* The graph reaches the right edge; beyond 1920px the writing remains near 1260px. */
/* Informational sheets use their full column; controls remain a readable width. */
/* the auth content's padding and its form's widths: system/modules/sections/auth-form/; its column: by role, components/sheet/ and sections/auth/ */
/* Approved auth spread overrides only the logged-out shell, at all profiles. */

`;
function adapt(source,name){
 let html=source;
 const oldDefault='body:not(:has(.screen:target)) #start{display:block}';
 if(!html.includes(oldDefault))throw Error(`${name}: missing walkthrough default`);
 html=html.replace(oldDefault,'body:not(:has(.screen:target,.screen.site-current)) #auth-login{display:block}');
 const oldStart=html;
 html=html.replace(new RegExp(openTag('section','screen','id="start"')+String.raw`[\s\S]*?<\/section>\s*`),'');
 if(html===oldStart)throw Error(`${name}: missing review index`);
 html=html.replace(new RegExp(openTag('p','aj-l-stage__caption motion-review-status')+String.raw`[\s\S]*?<\/p>`),'');
 html=html.replace(new RegExp(openTag('details','auth-preview')+String.raw`[\s\S]*?<\/details>`,'g'),'');
 html=html.replace(/<title>[^<]*<\/title>/,'<title>Journal</title>');
 const markup=html.replace(/<style[\s\S]*?<\/style>/g,'').replace(/<script[\s\S]*?<\/script>/g,'');
 if(/<link\b[^>]*rel="stylesheet"/.test(markup)||/<script\b[^>]*src=/.test(markup))throw Error(`${name}: external asset remains`);
 return {styles:[...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map(m=>m[1]).join("\n"),runtime:[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]).join("\n"),body:html.match(/<body[^>]*>([\s\S]*?)<\/body>/)[1].replace(/<script\b[\s\S]*?<\/script>/g,"")};
}
const layouts=Object.fromEntries(Object.entries(sources).map(([name,file])=>[
 name,adapt(fs.readFileSync(path.join(root,file),'utf8'),name)
]));
const common=layouts.mobile;
for(const [name,layout] of Object.entries(layouts)){
 if(layout.styles!==common.styles||layout.runtime!==common.runtime)throw Error(name+': shared payload differs');
}
const variants=Object.fromEntries(Object.entries(layouts).map(([name,layout])=>[name,layout.body]));
const encoded=JSON.stringify(variants).replaceAll('<','\\u003c');
const html=`<!doctype html>
<!-- GENERATED by scripts/build-website-preview.mjs. Open this file directly in a browser. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Journal</title>
<style>@layer tokens, base, legacy, layout, components, sections, pages;\n@layer legacy{html{overflow-y:scroll}}\n${common.styles}\n@layer legacy{${siteCss}}</style></head>
<body><main id="journal" data-site="website"></main>
<script>
function initializeJournalPreview(){
${common.runtime}
}
const variants=${encoded};
const host=document.getElementById('journal');
let active=null,changing=false,state=null;
// Stable viewport boundaries include the binding rail and original scrollbar
// allowance. Native inner scrolling must not change which profile is selected.
const profile=()=>innerWidth>=1239?'desktop':innerWidth>=739?'tablet':'mobile';
function showRoute(){
 const target=document.getElementById(location.hash.slice(1))||document.getElementById('auth-login');
 host.querySelectorAll('.screen.site-current').forEach(screen=>screen.classList.remove('site-current'));
 target?.classList.add('site-current');
}
addEventListener('hashchange',showRoute);
document.addEventListener('submit',event=>{
 const target=event.target.getAttribute('action');
 if(target?.startsWith('#')&&document.getElementById(target.slice(1))){
  event.preventDefault();location.hash=target;
 }
});
async function showProfile(){
 const next=profile();
 if(next===active||changing||window.__journalPreview?.recordingActive)return;
 changing=true;
 if(active){
  state=await window.__journalPreview?.snapshot()||state;
  window.__journalPreview?.destroy();
 }
 const route=location.hash||'#auth-login';
 host.innerHTML=variants[next];
 document.documentElement.dataset.motionReview='play';
 active=next;
 const target=route.slice(1);
 if(!document.getElementById(target))location.hash='auth-login';
 showRoute();
 initializeJournalPreview();
 window.__journalPreview?.restore(state);
 changing=false;
 if(profile()!==active)showProfile();
}
addEventListener('resize',showProfile);
addEventListener('journal-recorder-idle',showProfile);
showProfile();
</script></body></html>
`;
const output=path.join(root,'journal-website.html');
fs.writeFileSync(output,html);
console.log(`Built ${output} (${Buffer.byteLength(html)} bytes)`);

// The skeleton review (v4 round 10): the same website, but every page that loads shows its
// loading screen first, then the page. Hold keeps the skeleton up; Replay shows it again.
const oldRoute=`function showRoute(){
 const target=document.getElementById(location.hash.slice(1))||document.getElementById('auth-login');
 host.querySelectorAll('.screen.site-current').forEach(screen=>screen.classList.remove('site-current'));
 target?.classList.add('site-current');
}`;
if(!html.includes(oldRoute))throw Error('skeleton review: showRoute changed');
const skeletonRoute=`const LOADING={today:'today-loading',day:'day-loading',timeline:'timeline-loading',reflections:'reflections-loading',ask:'ask-loading',you:'you-loading','settings-visible':'settings-loading'};
const WAIT=1800;
let held=false,timer=0;
function show(target){
 host.querySelectorAll('.screen.site-current').forEach(screen=>screen.classList.remove('site-current'));
 target?.classList.add('site-current');
}
function showRoute(){
 clearTimeout(timer);
 const id=location.hash.slice(1);
 const target=document.getElementById(id)||document.getElementById('auth-login');
 const loading=LOADING[id]&&document.getElementById(LOADING[id]);
 const control=document.getElementById('skeleton-review');
 control.dataset.loads=loading?'yes':'no';
 if(!loading)return show(target);
 show(loading);scrollTo(0,0);
 if(!held)timer=setTimeout(()=>show(target),WAIT);
}
function hold(on){
 held=on;
 document.getElementById('skeleton-hold').setAttribute('aria-pressed',String(on));
 showRoute();
}
addEventListener('keydown',event=>{
 if(event.target.closest('input,textarea,[contenteditable]')||event.ctrlKey||event.metaKey||event.altKey)return;
 if(event.key==='h'||event.key==='H')hold(!held);
 if(event.key==='r'||event.key==='R')showRoute();
});`;
const reviewCss=`.screen:target:not(.site-current){display:none!important}
#skeleton-review{position:fixed;left:50%;bottom:8px;z-index:2147483647;transform:translateX(-50%);display:flex;align-items:center;gap:4px;padding:4px 4px 4px 12px;border:1px solid var(--ink);border-radius:999px;background:var(--paper);color:var(--ink);font:600 11px/1 system-ui,sans-serif;letter-spacing:.06em;text-transform:uppercase;box-shadow:0 2px 8px rgb(0 0 0/.12)}
#skeleton-review button{min-height:28px;padding:0 10px;border:1px solid transparent;border-radius:999px;background:none;color:inherit;font:inherit;letter-spacing:inherit;text-transform:inherit;cursor:pointer}
#skeleton-review button:hover{border-color:var(--ink)}
#skeleton-review button:focus-visible{outline:2px solid var(--ink);outline-offset:1px}
#skeleton-review button[aria-pressed="true"]{background:var(--ink);color:var(--paper)}
#skeleton-review[data-loads="no"] #skeleton-replay{opacity:.4}
@media (max-width:738px){#skeleton-review{left:auto;right:8px;top:12px;bottom:auto;transform:none;padding-left:4px}#skeleton-review>span{display:none}}`;
const control=`<div id="skeleton-review" role="group" aria-label="Skeleton review" data-loads="no"><span>Skeletons</span><button id="skeleton-hold" type="button" aria-pressed="false" onclick="hold(!held)" title="Keep the skeleton on screen (H)">Hold</button><button id="skeleton-replay" type="button" onclick="showRoute()" title="Show this page's skeleton again (R)">Replay</button></div>`;
const skeletons=html
 .replace('<!-- GENERATED by scripts/build-website-preview.mjs. Open this file directly in a browser. -->','<!-- GENERATED by scripts/build-website-preview.mjs: the skeleton review. Open this file directly in a browser. -->')
 .replace('<title>Journal</title>','<title>Journal skeletons</title>')
 .replace('</style></head>',`\n${reviewCss}</style></head>`)
 .replace('<main id="journal" data-site="website"></main>',`<main id="journal" data-site="website"></main>${control}`)
 .replace(oldRoute,skeletonRoute);
const skeletonOutput=path.join(root,'journal-skeletons.html');
fs.writeFileSync(skeletonOutput,skeletons);
console.log(`Built ${skeletonOutput} (${Buffer.byteLength(skeletons)} bytes)`);
