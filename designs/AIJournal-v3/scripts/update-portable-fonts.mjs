// Updating files is an explicit build step; importing portable-fonts is read-only.
import fs from 'node:fs';
import {portableFontCss} from './portable-fonts.mjs';
const root=new URL('../',import.meta.url);
const block=`/* PORTABLE FONTS START: generated by scripts/update-portable-fonts.mjs */\n${portableFontCss}\n/* PORTABLE FONTS END */\n`;
const replace=source=>source.includes('/* PORTABLE FONTS START:')?source.replace(/\/\* PORTABLE FONTS START:[\s\S]*?\/\* PORTABLE FONTS END \*\/\n?/,()=>block):source.replace(':root{',()=>block+'\n:root{');
const file=new URL('lock.css',root),source=fs.readFileSync(file,'utf8'),next=replace(source);
if(next!==source)fs.writeFileSync(file,next);
// The retained diagonal-light exploration remains independently portable.
const study=new URL('auth-alternatives/inset-backgrounds/05-glass-diagonal-light.html',root);
if(fs.existsSync(study)){
 const old=fs.readFileSync(study,'utf8');
 let html=old.includes('/* PORTABLE FONTS START:')?replace(old):old.replace('<style>','<style>\n'+block);
 html=html.replace('--f-prose: Constantia,"Palatino','--f-prose: Constantia,"Journal Portable Prose","Palatino')
  .replace('--f-label: "Segoe UI",system-ui','--f-label: "Segoe UI","Journal Portable Labels",system-ui')
  .replace('--f-hand:  "Ink Free","Segoe Script"','--f-hand:  "Ink Free","Journal Portable Hand","Segoe Script"');
 if(old!==html)fs.writeFileSync(study,html);
}
